import test from 'node:test';
import assert from 'node:assert/strict';
import {once} from 'node:events';
import {mockServer} from './mock-host.mjs';

test('mock host implements the unified Manor JSON contract', async t => {
  mockServer.listen(0, '127.0.0.1'); await once(mockServer, 'listening');
  t.after(() => {mockServer.closeAllConnections(); mockServer.close();});
  const base = `http://127.0.0.1:${mockServer.address().port}`;
  const state = () => fetch(`${base}/~/scry/manor/state.json`).then(res => res.json());
  const fixture = data => fetch(`${base}/managed-fixture`, {method: 'POST', body: JSON.stringify(data)});
  async function profileResult() {
    for (let i = 0; i < 100; i++) {
      const row = (await state()).managed.ships[0];
      if (!row.pending) return row;
      await new Promise(resolve => setTimeout(resolve, 25));
    }
    assert.fail('Profile confirmation did not arrive');
  }
  let id = 0;
  async function poke(json) {
    const path = `${base}/~/channel/contract-${++id}`;
    await fetch(path, {method: 'PUT', body: JSON.stringify([{id, action: 'poke', ship: 'siglup-narwet', app: 'manor', mark: 'manor-action', json}])});
    const res = await fetch(path), reader = res.body.getReader();
    const {value} = await reader.read();
    const event = JSON.parse(new TextDecoder().decode(value).split('data: ')[1].trim());
    await reader.cancel();
    await fetch(path, {method: 'PUT', body: JSON.stringify([{action: 'delete'}])});
    return event;
  }
  const ship = '~zod';
  assert.equal((await poke({'ship-add': {who: ship, endpoint: null}})).ok, 'ok');
  let current = await state();
  assert.ok(Array.isArray(current.pool));
  assert.ok(current.fleet && current.settings);
  assert.equal(current.managed.localOnly, true);
  assert.equal(current.managed.ships[0].transport, 'manor');
  assert.equal(current.managed.ships[0].endpoint, null);
  assert.equal(current.managed.ships[0].landing, 'landscape');
  assert.deepEqual(current.managed.ships[0].required, ['landscape']);
  assert.equal(current.controlled.landing, 'landscape');
  assert.deepEqual(current.controlled.required, ['landscape']);
  assert.equal((await poke({'ship-profile': {who: ship, name: 'Zod', avatar: 'https://example.com/a.png'}})).ok, 'ok');
  assert.equal((await state()).managed.ships[0].pending, 'profile');
  assert.equal((await state()).managed.ships[0].profile.displayName, 'Pilot');
  await profileResult();
  assert.equal((await poke({'ship-profile': {who: ship, name: null}})).ok, 'ok');
  await profileResult();
  current = await state();
  assert.deepEqual(current.managed.ships[0].profile, {displayName: null, avatar: {type: 'external', url: 'https://example.com/a.png'}});
  assert.equal((await poke({'ship-profile': {who: ship, avatar: null}})).ok, 'ok');
  await profileResult();
  assert.equal((await state()).managed.ships[0].profile.avatar, null);
  assert.ok((await poke({'ship-profile': {who: ship, avatar: 'data:image/png;base64,abc'}})).err);
  assert.ok((await poke({'ship-profile': {who: ship, upload: 'fake-bytes'}})).err);
  assert.equal((await poke({'ship-configure': {who: ship, landing: 'glurff', required: ['glurff']}})).ok, 'ok');
  assert.equal((await poke({pair: {controller: '~siglup'}})).ok, 'ok');
  assert.equal((await poke({'managed-configure': {landing: 'glurff', required: ['glurff']}})).ok, 'ok');
  assert.equal((await poke({pair: {controller: null}})).ok, 'ok');
  current = await state();
  assert.equal(current.controlled.controller, null);
  assert.equal(current.controlled.landing, 'glurff');
  assert.equal(current.managed.ships.length, 1, 'unpairing does not remove the local pool');
  assert.ok((await poke({'ship-add': {who: '~siglup', endpoint: {host: 'remote.example', port: 80, secure: false}}})).err);
  assert.ok((await poke({'ship-add': {who: '~siglup', endpoint: {host: 'localhost', port: 8101, secure: false}}})).err);
  const legacy = {...(await state()).managed.ships[0], transport: 'manor-moon', landing: 'glurff', required: ['glurff'], generation: 7, blocked: false};
  await fixture({ships: [legacy]});
  assert.equal((await poke({'ship-reconnect': {who: ship}})).ok, 'ok');
  assert.equal((await state()).managed.ships[0].transport, 'manor-moon');
  assert.equal((await poke({'ship-add': {who: ship, endpoint: {host: 'ship.example', port: 443, secure: true}}})).ok, 'ok');
  current = await state();
  assert.equal(current.managed.ships.length, 1);
  assert.equal(current.managed.ships[0].transport, 'manor-moon');
  assert.equal(current.managed.ships[0].generation, 7);
  assert.equal(current.managed.ships[0].landing, 'glurff');
  assert.deepEqual(current.managed.ships[0].required, ['glurff']);
  const claim = {entered: 1, expires: null};
  await fixture({ships: [{...legacy, claim}], profileFailure: 'Profile update failed'});
  assert.ok((await poke({'ship-add': {who: ship, endpoint: null}})).err);
  assert.ok((await poke({'ship-upgrade': {who: ship}})).err);
  assert.equal((await poke({'ship-profile': {who: ship, name: 'Not confirmed'}})).ok, 'ok');
  assert.ok((await poke({'ship-add': {who: ship, endpoint: null}})).err);
  const failed = await profileResult();
  assert.equal(failed.fault, 'Profile update failed');
  assert.deepEqual(failed.claim, claim);
  assert.equal(failed.blocked, false);
  assert.notEqual(failed.profile.displayName, 'Not confirmed');
  await fixture({ships: [legacy]});
  await fetch(`${base}/no-theseus`);
  assert.equal((await fetch(`${base}/~/scry/theseus/ui.json`)).status, 404);
  assert.equal((await fetch(`${base}/~/scry/manor/state.json`)).status, 200);
  assert.equal((await poke({'ship-remove': {who: ship}})).ok, 'ok');
  assert.equal((await state()).managed.ships.length, 0);

  const at = Date.now();
  await fixture({pairRequests: [{ship, at}, {ship: '~nec', at}]});
  assert.equal((await state()).managed.ships.length, 0, 'incoming requests do not register or unlock a ship');
  assert.ok((await poke({'ship-approve': {ship}})).err, 'admin commands use who, not ship');
  assert.ok((await poke({'ship-approve': {who: '~siglup'}})).err, 'approval requires a current request');
  assert.equal((await poke({'ship-reject': {who: '~nec'}})).ok, 'ok');
  assert.deepEqual((await state()).pairRequests, [{ship, at}]);
  assert.equal((await poke({'ship-approve': {who: ship}})).ok, 'ok', 'endpoint is optional');
  current = await state();
  assert.deepEqual(current.pairRequests, []);
  assert.equal(current.managed.ships[0].blocked, true, 'approval does not unlock');
  assert.equal(current.managed.ships[0].endpoint, null);
  const stale = {...current.managed.ships[0], ship: '~pilfep-sicted-mignes-magtel', claim: {entered: 1}, pending: 'session', online: true};
  await fixture({ships: [stale]});
  assert.ok((await poke({'ship-remove': {who: stale.ship}})).err);
  assert.equal((await poke({'ship-forget': {who: stale.ship}})).ok, 'ok', 'forget ignores claims, pending work and cached online status');
  assert.deepEqual((await state()).managed.ships, []);
  await fixture({pairRequests: [{ship, at}]});
  assert.equal((await poke({'ship-approve': {who: ship, endpoint: {host: 'ship.example', port: 443, secure: true}}})).ok, 'ok');
  assert.deepEqual((await state()).managed.ships[0].endpoint, {host: 'ship.example', port: 443, secure: true});
  assert.equal((await poke({'ship-profile': {who: ship, name: 'Late profile'}})).ok, 'ok');
  assert.equal((await poke({'ship-forget': {who: ship}})).ok, 'ok');
  await new Promise(resolve => setTimeout(resolve, 900));
  assert.deepEqual((await state()).managed.ships, [], 'a late result does not re-register a forgotten ship');
  const recorded = await (await fetch(`${base}/pokes`)).json();
  assert.equal(recorded.filter(row => row.kind === 'ship-unlock').length, 0);
});
